import fs from "node:fs";
import path from "node:path";

/**
 * Bakes the CRM's price record into the site at build time.
 *
 * The prices on this site sit in <title> tags and in JSON-LD, so they have to
 * be in the HTML Google is served. A runtime fetch would mean indexing a page
 * whose title says "Websites from $" and filling the number in afterwards, so
 * this runs once, before `next build`, and writes a plain module the pages
 * import like any other content file.
 *
 *   node scripts/pricing/fetch-pricing.mjs
 *   PRICING_URL=http://localhost:4321/pricing.json node scripts/pricing/fetch-pricing.mjs
 *
 * It fails the build rather than falling back to a hardcoded number. Nine
 * copies of every price drifting apart is the thing this exists to end, and a
 * silent fallback is how that started: the site would keep building, keep
 * serving yesterday's prices, and nobody would be told. A failed build is
 * loud, and loud is the point.
 */

const URL = process.env.PRICING_URL ?? "https://hq.rankify.com.au/api/pricing";
const OUT = path.join(process.cwd(), "src/content/pricing.generated.ts");

/** Every product the site renders. A missing one is a failed build, not a gap. */
const REQUIRED = [
  "website_build",
  "website_hosting",
  "free_homepage_offer",
  "shopify_build",
  "shopify_retainer",
  "shopify_hourly",
  "seo",
  "branding",
  "ad_sidekick",
];

/**
 * Thrown rather than exiting on the spot: calling process.exit() while a
 * fetch is still unwinding trips a libuv assertion on Windows and buries the
 * message we just printed under a stack trace.
 */
class PricingFailure extends Error {}

function die(message) {
  console.error(`\n  Pricing build step failed.\n\n  ${message}\n`);
  console.error(`  Source: ${URL}`);
  console.error(`  Contract: rankify-crm/docs/pricing-api.md\n`);
  console.error(`  Nothing was written. Fix the source rather than hardcoding a price —`);
  console.error(`  a number typed in here is a number that drifts.\n`);
  process.exit(1);
}

async function main() {
  const res = await fetch(URL, { headers: { Accept: "application/json" } }).catch((e) =>
    die(`Could not reach the pricing record: ${e.message}`),
  );

  if (!res.ok) {
    const body = await res.text().catch(() => "");
    die(
      res.status === 404
        ? `The CRM has no published price set (404).\n  Publish a version in Rankify HQ\n\n  ${body.slice(0, 200)}`
        : res.status >= 500
          ? `The CRM could not read its own store (${res.status}). That is an outage, not a price change: try again rather than typing a number in here.\n\n  ${body.slice(0, 200)}`
          : `The pricing record answered ${res.status}.\n\n  ${body.slice(0, 200)}`,
    );
  }

  const data = await res.json().catch(() => die("The pricing record was not valid JSON."));

  if (data.status !== "published") {
    die(`Refusing to build from a ${data.status} price set. Publish version ${data.version} first.`);
  }

  const missing = REQUIRED.filter((id) => !data.products?.[id]);
  if (missing.length) die(`The record is missing: ${missing.join(", ")}`);

  // An unresolved product carries no prices at all, by design: the CRM would
  // rather hand us nothing than a guess. Rendering "$undefined" is worse than
  // not building, so this stops here too.
  const unresolved = REQUIRED.filter((id) => data.products[id].status === "unresolved");
  if (unresolved.length) {
    die(
      `These prices are unresolved in the CRM and cannot be rendered: ${unresolved.join(", ")}\n` +
        `  Settle them in Rankify HQ`,
    );
  }

  const header = `// Generated by scripts/pricing/fetch-pricing.mjs — do not edit.
  //
  // Every price on this site comes from the CRM's price record, which is the one
  // place they live. Editing a number here is pointless: the next build
  // overwrites it, and the site would disagree with the invoice in the meantime.
  // Change it in Rankify HQ instead.
  //
  //   version ${data.version}, published, effective ${data.effective_from}
  //   generated ${new Date().toISOString()}
  //   from ${URL}

  `;

  const body = `export const PRICING = ${JSON.stringify(data, null, 2)} as const;

  export type Pricing = typeof PRICING;

  /** The version this build quoted from. Worth recording against a quote. */
  export const PRICING_VERSION = PRICING.version;

  const P = PRICING.products;

  /**
   * Shorthands for the prices the copy actually says, so a page reads
   * \`\${WEBSITE_FROM}\` rather than reaching four levels into the record.
   * Display strings are derived from cents by the CRM, so they cannot drift
   * from the amount charged.
   */
  export const WEBSITE_FROM = P.website_build.base_display;
  export const WEBSITE_PAGES_INCLUDED = P.website_build.pages_included;
  export const WEBSITE_EXTRA_PAGE = P.website_build.extra_page_display;
  export const HOSTING_PER_YEAR = P.website_hosting.per_year_display;
  export const SHOPIFY_FROM = P.shopify_build.from_display;
  export const SHOPIFY_RETAINER_FROM = P.shopify_retainer.from_display;
  export const SHOPIFY_HOURLY = P.shopify_hourly.per_hour_display;
  /**
 * ", 2 hour minimum" or "", depending on the record.
 *
 * The shared FAQ asserted a two hour minimum while the Casual tier card on
 * the same site said "no commitment" and named none. That sentence had
 * already carried two stale prices, so rather than pick a side the claim is
 * now rendered only when the record actually sets a minimum.
 */
export const SHOPIFY_HOURLY_MINIMUM = P.shopify_hourly.minimum_hours
  ? ", " + P.shopify_hourly.minimum_hours + " hour minimum"
  : "";

export const SEO_PER_PAGE = P.seo.per_page_per_month_display;
  export const SEO_MINIMUM_MONTHS = P.seo.minimum_term_months;
  export const BRANDING_FROM = P.branding.from_display;
  export const SIDEKICK_FROM = P.ad_sidekick.tiers[0].per_month_display;
  /**
 * "$99, $299 and $699" — the tier list as the pricing page's title says it.
 * Built here so the title cannot list a price the plan table no longer shows.
 */
export const SIDEKICK_TIERS = (() => {
  const d = P.ad_sidekick.tiers.map((t) => t.per_month_display);
  return d.length < 2 ? (d[0] ?? "") : d.slice(0, -1).join(", ") + " and " + d[d.length - 1];
})();

export const SIDEKICK_TO = P.ad_sidekick.tiers[P.ad_sidekick.tiers.length - 1].per_month_display;

  /**
   * The same prices as plain numbers, in dollars, for JSON-LD.
   *
   * schema.org wants a bare number for price, so each service page used to
   * carry a literal beside the display string it already imported -- which is
   * how /seo could say one price in its copy and 499 in its structured data
   * without anyone seeing the two disagree. Derived from the same cents, so
   * they cannot.
   */
  export const WEBSITE_FROM_AMOUNT = P.website_build.base_cents / 100;
  export const SEO_PER_PAGE_AMOUNT = P.seo.per_page_per_month_cents / 100;
  export const BRANDING_FROM_AMOUNT = P.branding.from_cents / 100;
  export const SHOPIFY_RETAINER_FROM_AMOUNT = P.shopify_retainer.from_cents / 100;
  export const SHOPIFY_HOURLY_AMOUNT = P.shopify_hourly.per_hour_cents / 100;

  /** Inclusions the record carries, for the copy that states them. */
  export const SHOPIFY_RETAINER_TIERS = P.shopify_retainer.tiers;
  export const BRANDING_PACKAGES = P.branding.packages;
  `;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, header + body);

  // The same numbers again, for checkout-api.
  //
  // That project deploys to Vercel on its own with no build step, so it cannot
  // run this script. Its copy is therefore committed, which is the one place in
  // this repo a generated file is: without it the functions would have no
  // prices at deploy time at all.
  //
  // Committing it also makes the charged amount change only on a deploy. A
  // charge read live from the record would mean a bad write in the CRM becomes
  // a wrong card debit, and a price published mid-checkout repricing someone
  // who is already on the payment page. The record is what we advertise; this
  // file is what we charge; _pricing.ts compares the two at runtime and shouts
  // when they disagree.
  const wb = data.products.website_build;
  const host = data.products.website_hosting;
  const offer = data.products.free_homepage_offer;

  const charge = `// Generated by scripts/pricing/fetch-pricing.mjs -- do not edit.
//
// Committed on purpose: checkout-api has no build step, so this is how the
// record reaches the endpoints that charge. Editing a number here is pointless
// and dangerous -- the next \`npm run pricing\` overwrites it, and until then
// the card is debited something the record never said.
//
// To change a price: publish it in Rankify HQ, run \`npm run pricing\`, commit
// the diff to this file, and deploy checkout-api. A price change is meant to
// be a deliberate deploy, not something that happens to a live checkout.
//
//   version ${data.version}, published, effective ${data.effective_from}
//   generated ${new Date().toISOString()}
//   from ${URL}

/** Website build, charged whether it is one page or ten. */
export const BASE_CENTS = ${wb.base_cents};
export const INCLUDED_PAGES = ${wb.pages_included};
export const EXTRA_PAGE_CENTS = ${wb.extra_page_cents};

/** Hosting, renewed yearly. */
export const HOSTING_CENTS = ${host.per_year_cents};

/**
 * The Stripe price this renews against, by lookup key.
 *
 * Read from the record rather than retyped because the key names a price that
 * already exists in Stripe: if hosting ever changes, this key must NOT change
 * with it, or the next deploy creates a second price and existing subscribers
 * are left pointing at the old one with nothing watching it.
 */
export const HOSTING_LOOKUP_KEY = ${JSON.stringify(host.stripe?.lookup_key ?? null)};

/** The free-homepage offer. */
export const OFFER_BUILD_DISCOUNT_CENTS = ${offer.build_discount_cents};
export const OFFER_HOSTING_FIRST_YEAR_CENTS = ${offer.hosting_first_year_cents};
export const OFFER_HOURS = ${offer.window_hours};
export const OFFER_COUPON_ID = ${JSON.stringify(offer.stripe?.coupon_id ?? null)};

/** The version these amounts came from, for the drift log. */
export const CHARGING_FROM_VERSION = ${data.version};
`;

  const CHARGE_OUT = path.join(process.cwd(), "checkout-api/api/_pricing.generated.ts");
  fs.mkdirSync(path.dirname(CHARGE_OUT), { recursive: true });
  fs.writeFileSync(CHARGE_OUT, charge);

  console.log(
    `pricing: v${data.version} (${data.effective_from}) → site + checkout-api` +
      `  websites ${data.products.website_build.base_display},` +
      ` hosting ${data.products.website_hosting.per_year_display},` +
      ` sidekick from ${data.products.ad_sidekick.tiers[0].per_month_display}`,
  );
}

try {
  await main();
} catch (err) {
  if (!(err instanceof PricingFailure)) {
    console.error(`
  Pricing build step failed: ${err.message}
`);
    process.exitCode = 1;
  }
} finally {
  // undici keeps the connection pooled, and Node tearing down on Windows with
  // a live socket trips a libuv assertion that buries the message above under
  // a C stack trace. Closing the dispatcher lets the process end quietly with
  // the exit code we actually set.
  await globalThis[Symbol.for("undici.globalDispatcher.1")]?.close?.().catch(() => {});
}
